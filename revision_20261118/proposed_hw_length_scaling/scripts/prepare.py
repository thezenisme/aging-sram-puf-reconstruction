"""Audit and export the existing paper matrices; never generate new code designs."""
from collections import Counter
from pathlib import Path
import json
import shutil
from common import ROOT, FORMAL, ACTIVE, CONFIGS, sha, save_json, load_source, gf2_rank, bits


def main():
    source_records = []
    audits = []
    for n, (suffix, source) in CONFIGS.items():
        frozen = ROOT / 'provenance' / f'n{n}'
        frozen.mkdir(parents=True, exist_ok=True)
        files = [f'h_matrix_1_2_{suffix}.h', f'g_matrix_1_2_{suffix}.h',
                 f'matrix_data_1_2_{suffix}.c']
        for name in files:
            src, dst = source / name, frozen / name
            if dst.exists():
                assert sha(src) == sha(dst), f'Source drift: {src}'
            else:
                shutil.copy2(src, dst)
            source_records.append(dict(source=str(src), snapshot=str(dst.relative_to(ROOT)), sha256=sha(dst)))
        data = load_source(n, frozen)
        k, m, z = data['K'], data['M'], data['Z']
        rows, grow = data['rows'], data['generator']
        assert z & (z-1) == 0 and n % z == 0 and m % z == 0 and k % 64 == 0
        assert all(len(set(r)) == len(r) and all(0 <= c < n for c in r) for r in rows+grow)
        hbits = [bits(r) for r in rows]
        gbits = [bits(r) for r in grow]
        assert all((h & g).bit_count() % 2 == 0 for h in hbits for g in gbits), 'G H^T != 0'
        columns = [0] * n
        for j, row in enumerate(grow):
            for c in row:
                columns[c] |= 1 << j
        candidates = {}
        for c, column in enumerate(columns):
            if column and column & (column-1) == 0:
                candidates.setdefault(column.bit_length()-1, c)
        assert len(candidates) == k, 'No systematic output coordinate for each information bit'
        positions = [candidates[j] for j in range(k)]
        if n == 4096:
            legacy = json.loads((FORMAL/'generated/matrix.json').read_text())
            assert rows == legacy['rows']
            # Preserve the production coordinate convention exactly.
            positions = legacy['information_positions']
            assert all(columns[c] == 1 << j for j,c in enumerate(positions))
        base, starts, prefix, degree_hi = [], [], 0, max(map(len, rows))
        assert degree_hi in (7, 8)
        assert set(map(len, rows)) <= {degree_hi-1, degree_hi}
        edge_file, row_file = [], []
        for rbase in range(m//z):
            row = rows[rbase*z]
            descriptors = [(c//z, c%z) for c in row]
            assert len({c for c,s in descriptors}) == len(row)
            for within in range(z):
                expected = [c*z + ((s+within) % z) for c,s in descriptors]
                assert rows[rbase*z+within] == expected, f'QC mismatch N={n} row={rbase*z+within}'
                assert prefix*z + within*len(row) == sum(map(len, rows[:rbase*z])) + within*len(row)
            starts.append(prefix)
            row_file.append((prefix<<4) | len(row))
            edge_file.extend(c*z+s for c,s in descriptors)
            base.append(descriptors)
            prefix += len(row)
        edges = sum(map(len, rows))
        assert edges == prefix*z
        target = ROOT/'generated'/f'n{n}'
        target.mkdir(parents=True, exist_ok=True)
        def hexfile(name, values, width):
            (target/name).write_text(''.join(f'{v:0{width}x}\n' for v in values), encoding='ascii')
        hexfile('base_edges.hex', edge_file, ((n-1).bit_length()+3)//4)
        hexfile('base_rows.hex', row_file, ((prefix-1).bit_length()+4+3)//4)
        hexfile('output_positions.hex', positions, ((n-1).bit_length()+3)//4)
        if n == 4096:
            for name in ['base_edges.hex', 'base_rows.hex', 'output_positions.hex']:
                assert (target/name).read_text() == (ACTIVE/'generated'/name).read_text(), name
        audit = dict(N=n, K=k, M=m, Z=z, N_base=n//z, M_base=m//z,
                     base_edges=prefix, edges=edges, max_row_degree=degree_hi,
                     row_degree_hist=dict(Counter(map(len,rows))),
                     col_degree_hist=dict(Counter(sum(c in row for row in rows) for c in range(n))),
                     rank=gf2_rank(hbits), generator_rank=k,
                     QC_verified=True, G_orthogonal=True, output_coordinates_verified=True,
                     contiguous_message_addresses_verified=True, production_hex_match=(n==4096))
        save_json(target/'matrix.json', dict(rows=rows, base=base, information_positions=positions))
        save_json(target/'config.json', audit)
        wrapper = f'''// Generated by scripts/prepare.py from audited paper matrix files.
module proposed_n{n} (
    input wire clk,rst,start, input wire [7:0] maxiter,
    input wire in_valid, input wire signed [7:0] in_llr,
    output wire ready,input_ready,busy,done,fail,
    output wire [7:0] iter_count, input wire out_ready,
    output wire out_valid,out_last,
    output wire [{(k//64-1).bit_length()-1}:0] out_index,
    output wire [63:0] out_word
);
    proposed_formal_stream #(.N({n}),.K({k}),.Z({z}),.BASE_EDGES({prefix}),
        .MAX_ROW_DEGREE({degree_hi}),.MATRIX_DIR("generated/n{n}")) decoder(.*);
endmodule
'''
        (target/'top.sv').write_text(wrapper, encoding='ascii')
        audits.append(audit)
        print(f'PREPARED N={n} K={k} Z={z} E={edges} rank={audit["rank"]} base={m//z}x{n//z}', flush=True)
    for name in ['formal_nms_core.sv', 'proposed_formal_stream.sv']:
        src = ACTIVE/'rtl'/name
        dst = ROOT/'provenance'/'production_rtl'/name
        dst.parent.mkdir(parents=True, exist_ok=True)
        if dst.exists():
            assert sha(src) == sha(dst), f'Production RTL drift: {src}'
        else:
            shutil.copy2(src,dst)
        source_records.append(dict(source=str(src), snapshot=str(dst.relative_to(ROOT)), sha256=sha(dst)))
    save_json(ROOT/'reports/matrix_audit.json', audits)
    save_json(ROOT/'provenance/manifest.json', dict(files=source_records,
        matrix_policy='Existing paper configurations; N=4096 uses the frozen production matrix. Not a fixed-base-matrix Z-only sweep.',
        production_project_untouched=True))


if __name__ == '__main__':
    main()
